export function buildSystemPrompt(language: SupportedLanguage): string {
  const languageInstruction = [
    `USER LANGUAGE: ${language} (${languageName(language)}).`,
    'Answer in this language unless the user explicitly asks to switch.',
    language === 'kk'
      ? 'For MRP/AЕК 2026, say "2026 жылға арналған АЕК мөлшері 4 325 теңге (2026 жылғы бюджет туралы заң)" and cite the Kazakhstan Tax Code context in Kazakh wording, including article references when relevant.'
      : '',
    terminologyPromptBlock(language),
  ].filter(Boolean).join('\n\n')

  return `${SYSTEM_PROMPT}\n\n${languageInstruction}`
}

