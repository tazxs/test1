async function main() {
  const apiKey = process.env.GEMINI_API_KEY
  if (!apiKey) {
    console.error('GEMINI_API_KEY is not set. Cannot generate embeddings.')
    process.exit(1)
  }

  const genAI = new GoogleGenerativeAI(apiKey)
  const model = genAI.getGenerativeModel({ model: 'text-embedding-004' })

  console.log(`Seeding ${TAX_LAW_ARTICLES.length} NK RK articles...`)

  for (const article of TAX_LAW_ARTICLES) {
    process.stdout.write(`  Embedding ${article.articleNumber}... `)

    const embeddingResult = await model.embedContent(
      `${article.articleNumber} ${article.title}\n${article.content}`,
    )
    const embedding = embeddingResult.embedding.values
    const vectorLiteral = `[${embedding.join(',')}]`

    // Upsert: delete existing row by articleNumber, then insert fresh
    await prisma.$executeRawUnsafe(
      `INSERT INTO tax_law_chunks (id, article_number, title, content, embedding, created_at, updated_at)
       VALUES (gen_random_uuid(), $1, $2, $3, $4::vector, NOW(), NOW())
       ON CONFLICT DO NOTHING`,
      article.articleNumber,
      article.title,
      article.content,
      vectorLiteral,
    )

    console.log('done')
  }

  console.log('Tax law seed complete.')
  await prisma.$disconnect()
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
